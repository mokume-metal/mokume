    // MARK: - 1 枚

    /// いま描いた絵を 1 枚、ファイルにする。
    ///
    /// ```swift
    /// func draw() {
    ///     background(26, 26, 31)
    ///     circle(width / 2, height / 2, 200)
    ///     if frameCount == 1 { save("first.png") }
    /// }
    /// ```
    ///
    /// 途中のディレクトリは無ければ作る。形式は PNG で、色空間は作業空間と同じ
    /// Display P3 ([ADR-0011] 決定 1)。**名前が `.svg` で終わるときだけ、絵でなく線を SVG に書く**
    /// (下の「SVG — 線そのものを書く」)。
    ///
    /// ## 出るのは画面と同じ絵である
    ///
    /// 書き出しは**画面へ差し出す絵と同じ道**から受け取る ([ADR-0024] 決定 6)。
    /// 効果も、明るさを写す段も、描く細かさと出す細かさの違いも、画面と同じに効く。
    /// 「画面ではこう見えるのに書き出すと違う」が起こらないのは、道が 1 本しか
    /// 無いからである。
    ///
    /// **透けたところは透けたまま残る。** 出力段がアルファの乗算を戻してから書くので
    /// ([ADR-0011] 決定 4)、``background(_:)-(LinearRGBA)`` に ``LinearRGBA/transparent`` を渡した
    /// 絵は、透過を持つ PNG になる。
    ///
    /// ## 書かれるのはこのフレームを描き終えた後
    ///
    /// 呼んだ時点では**予約するだけ**で、実際の書き込みはフレームの外で走る。
    /// ディスクの速さがフレームレートを縛らないためである。頼んだものが確かに
    /// ファイルになっているのは、``endRecord()`` から返った後と、スケッチが
    /// 終わった後である。
    ///
    /// **同じ行き先へ続けて頼むと、後に頼んだ絵が残る。** 同じ名前へ毎フレーム書いて、
    /// 外の仕組みに「いまの絵」を読ませる使い方ができる。同じ行き先へは 1 枚ずつ書き、
    /// 書いている間に頼まれたものは最後の 1 枚だけを書く — 間の絵がファイルに現れないことは
    /// あるが、書くのを待ってフレームが遅くなることは無い
    /// ([#1627](https://github.com/mokume-metal/mokume/issues/1627))。
    ///
    /// **止まっているスケッチは、そのフレームを描き終えた時点で書かれる。**
    /// ``noLoop()`` で止めた形も、止まっている間に `keyPressed()` から頼む形も、
    /// 次のフレームを待たない — 待たせると次が来ないので、終わりまで (終わりが
    /// 外から殺される形なら永久に) ファイルにならない
    /// ([#1300](https://github.com/mokume-metal/mokume/issues/1300))。GPU が描き損じた
    /// ときだけは別である (下の節)。
    ///
    /// ## 描けなかったフレームでは、次に描けた絵で書く
    ///
    /// 頼んだフレームを描けなかったとき (描画が転んだ・**GPU が仕事を打ち切った**
    /// [#2743](https://github.com/mokume-metal/mokume/issues/2743)) は、そのフレームの絵が仕上がって
    /// いないので、その絵では書かない。**次に描けたフレームの絵で書く。** 書いたときは、行き先と
    /// 頼んだフレーム・書いたフレームの番号を名指しして警告する (行き先ごとに 1 度。理由 — 描けなかった・
    /// GPU が打ち切った — を問わない)。GPU が打ち切ったことは、別に 1 度だけ警告で言う。
    ///
    /// - 毎フレーム違う名前で頼む形 (`save("f-\(frameCount).png")`) では、描けなかったフレームと
    ///   その次の 2 つの名前に、同じ絵が入りうる
    /// - 止まっているスケッチでは、面へ書き直す (画素を書くなど) か次のフレームを描くまで書かれない。
    ///   描画が転んだままなら、終わるときも転ぶ前の絵では書かない。どちらもしないまま終われば、終わる
    ///   ときに書けなかったと言う
    ///
    /// **作れない長さの名前は書かない。** ファイル名は 247 まで、作るディレクトリの名前は 1 つにつき 255 まで
    /// (ファイルシステムが数える長さで。濁点の付いた仮名などは 2 と数える)。越える名前や NUL を含む名前は、
    /// 頼んだ時点で長さを名指しして警告し、何も書かない。
    ///
    /// ## SVG — 線そのものを書く
    ///
    /// 名前が `.svg` で終わるなら、絵 (画素) でなく**図形の線を SVG に書く**。ペンプロッタやレーザーカッターへ
    /// 渡す線である。画面の絵は、頼んでも頼まなくても変わらない。
    ///
    /// ```swift
    /// func draw() {
    ///     save("flow.svg")  // draw() の先頭で頼む。この draw() が置く図形が書かれる
    ///     background(255)
    ///     noFill()
    ///     stroke(0)
    ///     strokeWeight(0.5)
    ///     for index in 0..<200 {
    ///         beginShape()
    ///         var x = Float(index) * 5
    ///         var y: Float = 0
    ///         for _ in 0..<100 {
    ///             vertex(x, y)
    ///             x += noise(x * 0.01, y * 0.01) * 4 - 2
    ///             y += 4
    ///         }
    ///         endShape()
    ///     }
    /// }
    /// ```
    ///
    /// 上の 200 本は、200 個の折れ線 (`<path>`) になる。線の太さ・色・端・折れ目は値として残る。
    ///
    /// ### 書かれるのは、呼んだ時点から `draw()` の終わりまで
    ///
    /// **意味は呼ぶ場所で決まる。** PNG の `save()` が「頼んだフレームの完成した絵」を書くのに対して、
    /// SVG はここが違う。
    ///
    /// - `draw()` の中で呼べば、**呼んだ時点から**その `draw()` の終わりまでに置いた図形を書く。呼ぶ前に置いた
    ///   図形は書かれない — 先頭で呼ぶのが作法で、呼ぶ前に図形を置いていれば 1 度だけ知らせる (毎フレームでは
    ///   ない)。背景は図形に数えないので、`background()` の後に呼んでも知らせない。**`background()` が画面の
    ///   絵を塗り直すときは、それより前に置いた図形も書かれない** (画面に無い線をペンプロッタが引かないように)
    /// - `draw()` の外 (`setup()`・`keyPressed()` など) で呼べば、**次の `draw()` を丸ごと**書く。呼んだフレームの
    ///   1 つ前の `draw()` の図形は入らない。この呼び方では知らせない。`noLoop()` で止めたスケッチは `redraw()` で
    ///   `draw()` が来るまで書かれず、来ないまま終わるときは書けなかったと言う
    ///
    /// 毎フレーム控えはしない — 頼まれていないフレームは、控える費用を払わない。複数のフレームにまたがって
    /// 1 枚に束ねる口は無い。
    ///
    /// **同じ `draw()` で同じファイルへ 2 回頼めば、先の頼みが書かれる** (後の頼みの図形は先の頼みにも入っているので、
    /// 何も欠けない)。後の頼みは何も変えず、そのことを行き先ごとに 1 度だけ知らせる。
    ///
    /// ### 何が書かれるか
    ///
    /// - **書く**: 矩形・楕円・弧・線・点・三角形・四角形、頂点で作る形 (開いた線・閉じた形・穴・曲線)、単色の
    ///   塗り、輪郭 (太さ・端・折れ目・破線)、変換、不透明度。図形 1 つが `<path>` 1 つになり、楕円と弧は
    ///   3 次ベジェで書く
    /// - **座標**: 1 単位は 1 画素・原点は左上・縦軸は下向き (SVG のユーザー単位と同じ)。`viewBox` は絵の大きさで、
    ///   縦軸は反転しない。変換は点に当てて書く
    /// - **色**: sRGB に写して書く。不透明度は `fill-opacity` / `stroke-opacity` に別の値で書く
    /// - **太さと破線の長さ**: 変換の拡大率を掛けた値 (画面の道でも、太さは変換に従う)。軸ごとに倍率が違う
    ///   変換では、面積の比の平方根で近似する。尖った折れ目の限界は SVG の `stroke-miterlimit` で切るので、
    ///   鋭い角の先の形は画面と少し違う
    /// - **曲線の継ぎ目**: `bezierVertex`・`curveVertex` などを刻んだ点の継ぎ目は、画面では `strokeJoin` によらず丸く
    ///   繋ぐが、SVG の線は 1 本に 1 つの継ぎ目の形しか持てないので、`strokeJoin` のまま書く。刻みが細かければ
    ///   違いは見えず、粗い曲線 (`curveDetail` を小さくしたもの) に `bevel` を指定したときだけ、面取りが見える
    /// - **点**: 点 1 つの輪郭 (`point`・`beginShape(.points)`・頂点が 1 つの形) は、画面と同じく端が `round` なら
    ///   円、それ以外は正方形で書く
    /// - **書かない** (書けなかった種類と数を、1 度だけ知らせる。画面には出る): 字・画像・保持した形
    ///   (`createShape`)・立体・画素の書き込み (`set`・`pixels` の添字と `fill`・`update`)・`filter`・`effects`・粒、
    ///   シェーダの下の図形、通常以外の混ぜ方・切り抜きの下の図形。貼る絵と勾配は**塗りにしか効かない**ので、
    ///   塗りだけを書かず、輪郭は書く。出力段 (効果・明るさの写し方・拡大) は通らない
    /// - **書かない (大きすぎる図形)**: 変換を当てた後の座標・線の太さ・破線の長さが約 1e12 画素以上の図形は、SVG の
    ///   数 (1/1000 まで整数で書く) に収まらないので、`0` へ潰さずに図形ごと落とし、種類と数を知らせる (画面には出る)。
    ///   数でない座標の図形は画面にも出ないので、知らせずに書かない
    /// - **見えないものは書かない**: 不透明度が 0 に近い塗りと輪郭は、書いても見えないので書かない。両方が見えない
    ///   図形は要素にならない
    /// - **書かず、知らせもしない**: `background()` の塗り。画面全体の塗りで、図形を置く口のどれも通らない —
    ///   SVG を開く道具の地の色になる
    /// - 頂点ごとに塗りの色を替えた形は、最初の頂点の色で塗る (そのことを知らせる)
    ///
    /// 同じ入力・同じ機械で書けば、文字列まで一致する (機械をまたぐ一致は約束しない)。書き込みは静止画と同じく
    /// フレームの外で走り、書けなかったことは静止画と同じ道で知らせる。`mokume render --out` は `.svg` を
    /// 受けない — 作品の中で `save("plot.svg")` を呼べば、`render` で走らせても書かれる。
    ///
    /// - Parameter path: 書き出す先。
    ///
    /// [ADR-0011]: https://github.com/mokume-metal/mokume/blob/main/docs/decisions/0011-color-model.md
    /// [ADR-0024]: https://github.com/mokume-metal/mokume/blob/main/docs/decisions/0024-extension-seams.md
    // shot: 撮れない 画面の絵を何も変えずにファイルを書く口で、書き終わる時点もフレームに紐づかない (確かなのは endRecord の後かスケッチの終わり) ので、書いたものを同じスケッチで読み戻して見せる絵も決まらない
    public func save(_ path: String) {
        guard let runtime = runningSketch else {
            return OutsideRun.log.warn(.save)
        }
        runtime.save(path)
    }

    // MARK: - 連番と動画

    /// 撮り続ける。**行き先の綴りが形を決める。**
    ///
    /// ```swift
    /// func draw() {
    ///     background(26, 26, 31)
    ///     circle(width / 2 + cos(time) * 200, height / 2, 80)
    ///
    ///     if frameCount == 1 { beginRecord("out/motion.mov") }  // 動きを 1 本にする
    ///     if frameCount == 120 { endRecord() }
    /// }
    /// ```
    ///
    /// `.mov` で終わる名前なら 1 本の動画に、ファイル名に `#` を含む名前なら 1 枚ずつの
    /// 連番になる (`"out/frame-####.png"`)。どちらでもない名前は**撮り始めずに知らせる**。
    ///
    /// **入るのは、呼んだフレームの絵から** ``endRecord()`` を呼んだフレームの前の絵まで
    /// である。上の例なら 1 フレーム目から 119 フレーム目までの 119 枚になる。直前のフレームで
    /// ``save(_:)`` を呼んでいても、1 枚目は変わらない。
    ///
    /// ``endRecord()`` は全部を書き終えてから返るので、撮れたものはその場で読み戻せる。
    /// 下の例は、円が 1 フレームに 1 つずつ増える絵を 2 フレーム目から撮り始め、5 フレーム目で
    /// 止めて、読み戻した連番を下に並べている。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     import Foundation
    ///
    ///     let folder = NSTemporaryDirectory() + "record-strip/"
    ///     var strip: [Image] = []
    ///
    ///     func draw() {
    ///         background(23, 26, 31)
    ///         noStroke()
    ///         fill(242, 115, 64)
    ///         for index in 0..<min(frameCount, 6) {
    ///             circle(40 + index * 64, 70, 48)
    ///         }
    ///
    ///         if frameCount == 2 { beginRecord(folder + "frame-##.png") }
    ///         if frameCount == 5 {
    ///             endRecord()  // 書き終えてから返る
    ///             strip = (0..<3).map { try! loadImage(folder + "frame-0\($0).png") }
    ///         }
    ///
    ///         stroke(90)
    ///         noFill()
    ///         for (index, shot) in strip.enumerated() {
    ///             image(shot, 20 + index * 125, 170, 110, 82.5)
    ///             rect(20 + index * 125, 170, 110, 82.5)
    ///         }
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 上の橙色の円は 1 フレームに 1 つずつ増えて 6 つで止まる。5 フレーム目から下に灰色の枠が 3 つ並び、読み戻した 3 枚の絵には円が左から 2 つ・3 つ・4 つある | frames=30 -->
    ///     ![上の橙色の円は 1 フレームに 1 つずつ増えて 6 つで止まる。5 フレーム目から下に灰色の枠が 3 つ並び、読み戻した 3 枚の絵には円が左から 2 つ・3 つ・4 つある](https://i.gyazo.com/661d65032fba4c70ad1f4c448f9a1cc1.gif)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// ## 連番 — 番号は撮った順に並ぶ
    ///
    /// **`#` の並びが番号の桁になる。** 桁を揃えるので、名前順に並べたときが撮った順に
    /// なる。番号はこの録りの中での通し番号で、0 から始まる (フレーム番号ではない —
    /// 途中から撮り始めても連番は 0 から続く)。
    ///
    /// **番号が入るのはファイル名の `#` だけである。** 置き場のフォルダの名前にある `#` は
    /// 場所の一部として残る — `"take#1/f-##.png"` なら `take#1` の中に `f-00.png`・
    /// `f-01.png`… が並ぶ。
    ///
    /// 番号の入る場所が無い名前を受けてしまうと全部のフレームが同じ名前になり、最後の
    /// 1 枚しか残らない — 撮れているつもりで撮れていない、といういちばん分かりにくい
    /// 壊れ方になる。だから断る。フォルダの名前にしか `#` が無い名前 (`"take#1/still.png"`)
    /// も、ファイル名に番号の入る場所が無いので断る。
    ///
    /// ## 動画 — 同じ入力からは同じ動きが出る
    ///
    /// 符号化は ProRes 4444 (.mov) で固定で、選べない。**選べる形にすると、書き出した
    /// 動きが再現するかどうかが名前の付け方で変わる** ([ADR-0025] 決定 3)。同じ入力から
    /// 2 回書き出して測ると、H.264 は画素が一致せず、ProRes 4444 はデコードした画素と時刻が
    /// 一致した。代わりに**大きい** (480x270 の 90 枚で 3 MB ほど。中身で変わる) —
    /// 配布する形式ではなく、元にする形式である。
    ///
    /// **一致するのは中身で、ファイルそのものではない。** 容れ物に刻まれる作成・更新時刻には
    /// 書き出した時刻の秒が入るので、違う秒に書いた 2 本を `shasum` で比べても同じにはならない。
    /// 同じ動きが出たかは、デコードした画素と時刻で比べる。
    ///
    /// **透けたところは透けたまま残る** (静止画と同じ)。
    ///
    /// 時刻は**そのフレーム自身の時刻**から作る。描けなかったフレームがあっても残った絵の
    /// 時刻は動かず、その 1 枚が長く映るだけになる — 詰めて並べると、動きが少しずつ
    /// 早回しになる。入らなかった枚数は ``endRecord()`` のときに知らせる。
    ///
    /// **時刻は 90 000 分の 1 秒の刻みで書く。** 90 000 を割り切る fps (24・30・48・60・1000 など)
    /// なら 1 枚の長さは全部同じになり、割り切らない fps (7 など) では 1 刻み (約 11 µs) の揺れが
    /// 残る。fps が 90 000 を越えると 1 フレームぶん (1/fps 秒) が 1 刻みより短くなって書き表せない
    /// ので、時計によらず撮り始めずに知らせる (フレーム番号の時計なら、隣のフレームが同じ時刻に
    /// なって枚が消える)。
    ///
    /// 時計が実時間なら (画面に出しながら走らせる経路) 実時間のまま入る。同じ動画をもう
    /// 一度出したいなら、フレーム番号から時刻を導く時計で走らせる ([ADR-0025] 決定 1)。
    ///
    /// ## 追いつかないときは、フレームが遅くなる
    ///
    /// 書き込みが間に合わないと、抱える枚数が上限に達したところで次のフレームが待つ。
    /// **メモリは伸びない代わりに、絵が遅くなる。** 長く撮っても走らせ続けられることを、
    /// 伸び続けないことのほうで担保している。
    ///
    /// ## 動画は、閉じ終えるまで前のファイルを残す
    ///
    /// `"out/motion.mov"` のように 1 本のファイルへ書く録りは、**行き先の隣の隠した一時ファイルへ書き、
    /// ``endRecord()`` で書き損じなく閉じ終えたときだけ、1 回の置き換えで行き先に置く** (`.gif`・`.mp4` も同じ)。
    /// 同じ名前へ撮り直すのは今までどおり上書きだが、書いている間も、書き損じたときも、プロセスが落ちたときも、
    /// 行き先に前からあったファイルはそのまま残る。書き損じとは、1 枚でも書けなかった枚があった録り・閉じ切れなかった録り・
    /// 閉じたのに空だった録り・置き換えが断られた録りで、警告は行き先の名前を言い、前のファイルが残ったことも言う。
    /// 一時ファイルを書いている最中に落ちたときの残りは、次に同じ名前へ書く録りが片付ける。
    /// 連番 (`"out/frame-####.png"`) は 1 枚ずつ行き先へ書くので、この保証の外である。
    ///
    /// **代償が 2 つある。** 隣の一時ファイルを作る準備を `beginRecord` の時点でするので、親のディレクトリの作成も
    /// 撮り始めに前倒しになる (1 枚も描かれない録りでも空のディレクトリが残る)。書いている間は前のファイルと一時ファイルが
    /// 並ぶので、ディスクの要りようが一時的に倍になる。`.gif` は、書けないディレクトリにある書き込める既存ファイルを
    /// 上書きできなくなった (隣に一時ファイルを作れない。`.mov`・`.mp4` は元から断っていた)。

    /// ## 作れない長さの名前は、撮り始めない
    ///
    /// 1 枚目のファイル名が長すぎるときは、撮り始めずに警告する。ファイル名は連番で 247、`.mov` で 255 まで、
    /// 作るディレクトリの名前は 1 つにつき 255 まで (ファイルシステムが数える長さで。濁点の付いた仮名などは
    /// 2 と数える)。NUL を含む名前も撮り始めない。**録りの途中で番号の桁が伸びて越える回は、枚数が先に
    /// 分からないので撮り始める前には断らず、その枚を書き損じとして知らせる。**
    ///
    /// ## `.svg` の連番は撮り始めない
    ///
    /// 連番が書くのは PNG の絵なので、`"out/frame-####.svg"` は撮り始めずに知らせる (受けると、PNG の中身が
    /// `.svg` の名前で並ぶ)。図形の線を SVG に書くのは ``save(_:)`` で、連番のベクターは今は無い。
    ///
    /// - Parameter pattern: 行き先。`.mov` なら動画、ファイル名に `#` を並べれば連番。
    ///
    /// - Note: **名前は手本と同じでも、意味は手本と違う。** Processing の
    ///   `beginRecord(renderer, filename)` は、描く命令を PDF や SVG のレンダラへ写して**ベクタで
    ///   記録する**口で、引数が 2 つある。こちらは**絵 (画素) を 1 フレームずつ**動画か連番の画像に
    ///   書き、引数は行き先の 1 つだけである。手本の 2 つの引数を渡す呼び出しは、コンパイルで止まる
    ///   (黙って別の意味にはならない)。始まりと終わり (``endRecord()``) の対で、ファイル名の `#` を
    ///   番号に置き換える綴りは手本と同じである。連番だけなら Processing の `saveFrame` を毎フレーム
    ///   呼ぶ形に当たるが、動画へ書く口と終わりの口が要るので、手本の中では同じ形の `beginRecord` の
    ///   名前を採った ([ADR-0020] 決定 1)。
    ///
    /// [ADR-0020]: https://github.com/mokume-metal/mokume/blob/main/docs/decisions/0020-api-naming-and-surface.md
    /// [ADR-0025]: https://github.com/mokume-metal/mokume/blob/main/docs/decisions/0025-determinism-levels.md
    // shot: 1 snippet=5f85730d
    public func beginRecord(_ pattern: String) {
        guard let runtime = runningSketch else {
            return OutsideRun.log.warn(.beginRecord)
        }
        runtime.beginRecord(pattern)
    }

    /// 連番や動画を止める。**頼んだ全部がファイルになってから返る。**
    ///
    /// 「呼んだら書かれる」ように見える面が「あとで書かれる」実装だと、止めるときに
    /// 壊れる。ここから返った後にプロセスを終えても、要求した最後の 1 枚まで残っている。
    /// **始まりだけでなく終わりも面の一部**である。
    ///
    /// 待つのはまだ書けていない枚数ぶんだけなので、撮り終わりに 1 度だけフレームが
    /// 伸びる。返った直後に連番を読み戻す例と絵は ``beginRecord(_:)`` にある。
    // shot: 参照 beginRecord(_:)
    public func endRecord() {
        guard let runtime = runningSketch else {
            return OutsideRun.log.warn(.endRecord)
        }
        runtime.endRecord()
    }
}
