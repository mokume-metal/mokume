import MokumeDiagnostics

// 進行を止める・戻す・1 枚だけ描き直す。**説明文の正本はこちら** ([ADR-0020] 決定 4)。
//
// [ADR-0020]: https://github.com/mokume-metal/mokume/blob/main/docs/decisions/0020-api-naming-and-surface.md
extension SketchPart {

    /// 以後 ``Sketch/draw()`` を呼ばない。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     func setup() {
    ///         noLoop()
    ///     }
    ///
    ///     func draw() {
    ///         background(23, 26, 31)
    ///         noStroke()
    ///         fill(242, 115, 64)
    ///         circle(20 + Float(frameCount) * 6, 170, 40)
    ///         fill(255)
    ///         textSize(28)
    ///         text("\(frameCount)", 20, 50)
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 左上に 1 と出て、橙色の円が左端に描かれたまま、どの枚も変わらない | frames=60 still="setup() で止めたので、1 度だけ描いた 1 枚目が続くのが正しい" -->
    ///     ![左上に 1 と出て、橙色の円が左端に描かれたまま、どの枚も変わらない](https://i.gyazo.com/02542072177299907cc659b432f82179.gif)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// **`setup()` で呼んでも、``Sketch/draw()`` は 1 度だけ呼ばれる。** 何も描かないまま
    /// 止まると絵が出ないためで、手本と同じ振る舞いである。``Sketch/draw()`` の中で呼べば、
    /// そのフレームを描き切ってから止まる。下は 30 枚目の ``Sketch/draw()`` の中で呼んだもの。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///     noStroke()
    ///     fill(242, 115, 64)
    ///     circle(20 + Float(frameCount) * 6, 170, 40)
    ///     fill(255)
    ///     textSize(28)
    ///     text("\(frameCount)", 20, 50)
    ///     // 30 枚目を描き切ってから止まる
    ///     if frameCount == 30 {
    ///         noLoop()
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 橙色の円が左から右へ進み、左上の数が 30 になったところで円も数も止まる | frames=60 -->
    ///     ![橙色の円が左から右へ進み、左上の数が 30 になったところで円も数も止まる](https://i.gyazo.com/c164a40b7e8a58f7a4fb4a199c057d1c.gif)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// 止まっている間、絵は変わらない — フレーム番号も時刻も進まず、続けて書き出した
    /// 絵は同じバイト列になる。
    ///
    /// 描画を止めずに ``time`` だけを止めるなら ``pauseTime()`` を使う。
    ///
    /// ## 止まっていても入力は届く
    ///
    /// ``Sketch/mousePressed()`` などのコールバックは呼ばれ続ける。止めたスケッチを動かし直す
    /// ``loop()`` / ``redraw()`` は、そこから呼ぶ。
    ///
    /// ```swift
    /// func mousePressed() {
    ///     redraw()  // 押すたびに 1 枚だけ描き直す
    /// }
    /// ```
    ///
    /// ただし止まっている間のコールバックは**フレームの外**で呼ばれる。そこで置いた図形は
    /// 次に描くフレームまで出ず、**切り抜きも無い状態で置かれる** — そこで書いた
    /// ``clip(_:_:_:_:)`` は警告して無視され、前の ``Sketch/draw()`` の切り抜きも効かない。
    /// **変換は効く** — そこで書いた ``translate(_:_:)`` などの変換や ``push(fileID:line:)`` は、その後に
    /// 置いたものへ焼き付く。ただし**コールバックを抜けるときに戻り**、コールバック 1 つごとに
    /// 変換の無い状態から始まる。前の ``Sketch/draw()`` が最後に残した変換 (戻し忘れた
    /// ``push(fileID:line:)`` の後の分も) は効かず、同じ呼び出しで続けて配る次のコールバックにも
    /// 漏れない。``screenX(_:_:)`` などで読む座標は、そのコールバックで書いた変換だけを通す。
    /// 置いた立体は**光も周囲も無い状態で置かれ**、前の ``Sketch/draw()`` の光は
    /// 当たらない (塗りの色のまま出る)。塗りや線の色は前の ``Sketch/draw()`` のものが残る。描くのは
    /// ``Sketch/draw()`` に任せる。
    ///
    /// **ループ中 (と、``redraw()`` を頼んだ後の止まっているスケッチ) のコールバックは、フレームの内側で
    /// 配られる**ので、光・視点・切り抜きなども効く。そこでも**コールバック 1 つごとに、書いたシーンの記述
    /// (変換・光・視点・切り抜き・材質・影・周囲・効果) を抜けるときに戻す** — 書いた変換・光・切り抜きは、
    /// そのコールバックの中で置いたものにだけ効き、同じフレームの ``Sketch/draw()`` には効かない
    /// (Processing・p5.js と同じ結果・[#3408])。塗りなどの描き方は戻らない。
    ///
    /// [#3408]: https://github.com/mokume-metal/mokume/issues/3408
    ///
    /// 置いたものが次に描くフレームへ持ち越されるのは、止まっている間のコールバックと
    /// ``Sketch/setup()`` が**持ち越しを約束する区間**だからである。``redraw()`` を呼ばずに置き続けると、
    /// 置いたものは上限なく溜まり続ける。コールバックの中で起こした `Task` の続きは区間の外で、
    /// そこで置いた図形・絵・背景と書いた画素は、警告して置かない。
    ///
    /// ## 呼べる場所
    ///
    /// **進行の 3 つの口 (これと ``loop()`` / ``redraw()``) が効くのは、``Sketch/setup()``・
    /// ``Sketch/draw()``・入力のコールバックの中から呼んだときだけである。** それ以外の場所から
    /// 呼ぶと何もせず、そのことを標準エラーで知らせる。
    ///
    /// **そこで起こした `Task` の中も、外に数える。** `Task` の中身が走るのは起こした
    /// コールバックが返った後で、そのときにはもう呼び出しの中ではない。
    ///
    /// 待つ読み込みの口 (``requestImage(_:)`` など) は `Task` から呼べるが、あちらは
    /// 絵を描かず値を返すだけなので `Task` へ持ち越せる。進行の口は持ち越さない —
    /// `Task` から触れると、どのフレームが描き直されるかが `Task` に番が回る時機で
    /// 決まるためである。
    ///
    /// ## 外からの停止とは別に持つ
    ///
    /// ホストが `SketchRuntime.pause()` / `resume()` で止めて再開しても、ここで止めた
    /// スケッチは止まったままである。理由は `SketchRuntime.resume()` の説明にある。
    // shot: 1 snippet=0c47b4c6
    // shot: 2 snippet=61f798db
    public func noLoop() {
        guard let runtime = runningSketch else {
            return OutsideRun.log.warn(.noLoop)
        }
        runtime.noLoop()
    }

    /// ``noLoop()`` で止めた進行を戻す。回っている間に呼んでも何もしない。
    ///
    /// ```swift
    /// func mousePressed() {
    ///     loop()
    /// }
    /// ```
    ///
    /// 戻った後の最初の 1 枚の ``deltaTime`` は**目標の 1 フレームぶん**
    /// (`1 / settings.frameRate` 秒) で、止まっていた間の時間は乗らない。``time`` も含めて、
    /// その 1 枚の値は ``redraw()`` で描き直した 1 枚と同じになる (``redraw()`` の
    /// 「描き直しの 1 枚の時刻」)。2 枚目からは、ふだんどおり前のフレームからの経過である。
    ///
    /// **効くのは ``Sketch/setup()``・``Sketch/draw()``・入力のコールバックの中から呼んだときだけ**で、
    /// そこで起こした `Task` から呼んでも回り出さない (``noLoop()`` の「呼べる場所」)。
    // shot: 撮れない 止めた後に呼べる入力のコールバックが撮影では来ない (撮る側は入力を配らず、setup() / draw() で呼んでも同じ呼び出しの noLoop() を打ち消すだけで絵に違いが出ない)
    public func loop() {
        guard let runtime = runningSketch else {
            return OutsideRun.log.warn(.loop)
        }
        runtime.loop()
    }

    /// ``noLoop()`` で止めている間に、``Sketch/draw()`` を 1 度だけ呼ぶよう頼む。
    ///
    /// 描かれるのは次のフレームで、何度呼んでも 1 度である。コールバックから呼んだ
    /// ときは、そのコールバックと同じフレームで描かれる。
    ///
    /// **回っている間と、``Sketch/draw()`` の中では何もしない** — どちらも、頼まなくても
    /// 描かれている (または描いている最中の) フレームだからである。
    ///
    /// **効くのは ``Sketch/setup()``・``Sketch/draw()``・入力のコールバックの中から呼んだときだけ**で、
    /// そこで起こした `Task` から呼んでも描き直さない (``noLoop()`` の「呼べる場所」)。
    ///
    /// ## 描き直しの 1 枚の時刻
    ///
    /// **1 回の描き直しで、回っているときの 1 枚ぶん進む。** その 1 枚の ``deltaTime`` は
    /// 目標の 1 フレームぶん (`1 / settings.frameRate` 秒・60 fps なら約 0.0167 秒) で、止めていた
    /// 長さによらない。`deltaTime` (秒) で積んで動かすものは、描き直すたびに 1 枚ぶんずつ動く。
    ///
    /// ``time`` は時計によって進み方が違う:
    ///
    /// - 窓に出して動かしているとき (実時間の時計) — **止めていた時間ごと進む。** ``time`` は
    ///   実際に流れた時間なので、描き直した 1 枚で止めていたぶんに追いつく。`time` から
    ///   導いた動きは、その 1 枚で止めていたぶんだけ先へ飛ぶ
    /// - フレーム番号から時刻を導く時計 (書き出しと検査の既定) — **1 フレームぶんだけ
    ///   進む。** 止めている間はフレームが進まないので、止めていた時間はどこにも現れない
    ///
    /// ``deltaTime`` の値はどちらの時計でも同じである。
    // shot: 撮れない 止めている間に呼べる入力のコールバックが撮影では来ない (撮る側は入力を配らず、回っている間と draw() の中では何もせず、setup() で止めた後に呼んでも必ず描かれる 1 枚目に畳まれる)
    public func redraw() {
        guard let runtime = runningSketch else {
            return OutsideRun.log.warn(.redraw)
        }
        runtime.redraw()
    }
}
