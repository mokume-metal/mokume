// 道 (``Path``)。
extension SketchPart {
    /// 頂点を並べた形を、**道**として記録する。長さを測り、道の上の点を引き、内側かを問える。
    ///
    /// 閉包の中で ``beginShape(_:)`` から ``endShape(_:)`` まで並べた頂点 (``beginContour()``・
    /// ``bezierVertex(_:_:_:_:_:_:)``・``quadraticVertex(_:_:_:_:)``・``curveVertex(_:_:)`` を含む) が、道になる。
    /// 記録するのは**形だけ**で、色や線の太さなどの設定は道に入らない — 閉包の中で変えた ``fill(_:)-(LinearRGBA)`` などは、
    /// 抜けると元に戻る。描くのは ``shape(_:_:_:)-(Path,_,_)`` で、そのときの塗りと線に従う。
    ///
    /// 4 つの頂点を閉じた正方形は、1 辺ずつ辿った長さ 400 の道になる。`path.point(at: 0.25)` は弧長で 4 分の 1
    /// 進んだ角の点を返し、`path.contains([50, 50])` は内側かを答える。開いたままの形は、閉じる辺を長さに数えない。
    ///
    /// - 入口で変換は単位に戻り、中で書いた ``translate(_:_:)`` などは頂点に焼き込まれる (``createShape(_:)`` と同じ)。
    ///   平面の道なので、``rotateX(_:)`` などの変換が持つ奥行きの成分は落ちて、平面に写した座標が残る。
    /// - 部分道が複数あるとき (``beginShape(_:)`` を何度か呼んだとき、``beginContour()`` で穴を置いたとき)、
    ///   全部を 1 つの形とみなし、回り数が 0 でない所を内側とする。
    /// - ``bezier(_:_:_:_:_:_:_:_:)`` は、道に入る。``bezierVertex(_:_:_:_:_:_:)`` で書いた曲線と同じに、開いた部分道
    ///   として記録する。
    /// - **残るのは座標だけ。** 頂点ごとに違う塗りの色・貼る絵の読み取り位置 (``vertex(_:_:_:_:)``)・面の向き
    ///   (``normal(_:_:_:)``) は、輪郭は道に入っても値は残らず、種類ごとに 1 度だけ知らせる。
    /// - **基本図形 (``rect(_:_:_:_:)``・``circle(_:_:_:)``・``line(_:_:_:_:)``・``arc(_:_:_:_:_:_:)`` など。
    ///   ``bezier(_:_:_:_:_:_:_:_:)`` は上のとおり入る)・字・画像・立体は、道に入らず、描かれない。**種類ごとに 1 度
    ///   だけ知らせる。道には ``beginShape(_:)`` で並べた輪郭だけが入る。奥行きのある頂点も断る。効果の頼みや塗り直しは、
    ///   ``createShape(_:)`` の中と同じく効かない。
    /// - 中で ``shape(_:_:_:)-(Path,_,_)`` を呼ぶと、描き方 (``fill(_:)-(LinearRGBA)`` や ``stroke(_:)-(LinearRGBA)`` の有無)
    ///   に依らず、その道の部分道が、いまの変換を掛けて 1 回ずつ足される。非有限の座標になる部分道は飛ばして、1 度だけ
    ///   知らせる。
    /// - **部分道の並びは、足された順である。** ``shape(_:_:_:)-(Path,_,_)`` はその場で足し、開いた
    ///   ``beginShape(_:)`` は ``endShape(_:)`` で足すので、`beginShape()` の途中で `shape(path)` を呼ぶと、
    ///   `path` の部分道が先で、外の形が後になる。``Path/point(at:)`` が辿る順もこれである。
    /// - 中で ``createShape(_:)`` を呼べるが、中の形の輪郭は外の道へ入らない (逆に ``createShape(_:)`` の中の
    ///   ``createPath(_:)`` も同じ)。
    ///
    /// 走っている実行の面を取れない所 (初期化子の中・後片付けの後など) で呼ぶと、落ちずに空の道を返し、1 度だけ
    /// 警告する。中身は呼ばれる。
    // shot: 撮れない 道を作る口で、描く結果が無い (描くのは shape(path)。作例は #3562 が持つ)
    public func createPath(_ body: () -> Void) -> Path {
        guard let canvas = Self.liveCanvas(.make(returning: "an empty path")) else {
            body()
            return Path()
        }
        return canvas.createPath(body)
    }

    /// 道を描く。
    ///
    /// 塗りと線は、いまの ``fill(_:)-(LinearRGBA)`` と ``stroke(_:)-(LinearRGBA)`` に従う。道は見た目を持たない。
    /// (`x`, `y`) は道の原点の置き場所で、省けば原点 (0, 0) になる。いまの変換が効く。
    ///
    /// **1 つの ``beginShape(_:)`` (``beginContour()`` の穴を含む) から作った道は、同じ ``beginShape(_:)`` をその場で描いた
    /// ときと同じ画素になる。** 別々の ``beginShape(_:)`` を 1 つの道にした場合は、そうならない: 全部を 1 つの形として
    /// 回り数で塗る (逆向きに重なる 2 つの四角は、重なりが抜ける)・塗りを全部描いてから線を描く (重なりの順が変わる)・
    /// 線は部分道ごとに 1 つの図形として引く (部分道どうしの線が重なる所は 2 回混ざる)。3 点に満たない部分道 (線・点)
    /// は塗りに使わず、線だけを引く。``VertexKind/quads`` など四角の読み方は、四角の継ぎ目の扱いを失い、折れ線の周に
    /// なる。SVG へ書き出すときも、塗りは 1 つの図形、線は部分道ごとの図形になる。
    ///
    /// ``createPath(_:)`` の中で呼ぶと、描かずに、外の道へ部分道を足す。
    // shot: 撮れない 作例 (道に沿って動くもの・破線) は #2432・#3562 が持つ。同じ beginShape との画素の一致は PathTests が見る
    public func shape(_ path: Path, _ x: some ScalarConvertible = 0, _ y: some ScalarConvertible = 0) {
        guard let canvas = Self.liveCanvas() else { return }
        canvas.shape(path, x, y)
    }
}
