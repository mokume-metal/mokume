// 道 (``Path``)。
extension SketchPart {
    /// 頂点を並べた形を、**パス**として記録する。長さを測り、パスの上の点を引き、内側かを問える。
    ///
    /// 閉包の中で ``beginShape(_:)`` から ``endShape(_:)`` まで並べた頂点 (``beginContour()``・
    /// ``bezierVertex(_:_:_:_:_:_:)``・``quadraticVertex(_:_:_:_:)``・``curveVertex(_:_:)`` を含む) が、パスになる。
    /// 記録するのは**形だけ**で、色や線の太さなどの設定はパスに入らない — 閉包の中で変えた ``fill(_:)-(LinearRGBA)`` などは、
    /// 抜けると元に戻る。描くのは ``shape(_:_:_:)-(Path,_,_)`` で、そのときの塗りと線に従う。
    ///
    /// 4 つの頂点を閉じた正方形は、1 辺ずつ辿った長さ 400 のパスになる。`path.point(at: 0.25)` は弧長で 4 分の 1
    /// 進んだ角の点を返し、`path.contains([50, 50])` は内側かを答える。開いたままの形は、閉じる辺を長さに数えない。
    ///
    /// - 冒頭で変換は単位に戻り、中で書いた ``translate(_:_:)`` などは頂点に焼き込まれる (``createShape(_:)`` と同じ)。
    ///   平面のパスなので、``rotateX(_:)`` などの変換が持つ奥行きの成分は落ちて、平面に射影した座標が残る。
    /// - サブパスが複数あるとき (``beginShape(_:)`` を何度か呼んだとき、``beginContour()`` で穴を置いたとき)、
    ///   全部を 1 つの形とみなし、回り数が 0 でない所を内側とする。
    /// - ``bezier(_:_:_:_:_:_:_:_:)`` は、パスに入る。``bezierVertex(_:_:_:_:_:_:)`` で書いた曲線と同じに、開いたサブパス
    ///   として記録する。
    /// - **残るのは座標だけ。** 頂点ごとに違う塗りの色・貼るテクスチャの読み取り位置 (``vertex(_:_:_:_:)``)・面の向き
    ///   (``normal(_:_:_:)``) は、輪郭はパスに入っても値は残らず、種類ごとに 1 度だけ報告する。
    /// - **基本図形 (``rect(_:_:_:_:)``・``circle(_:_:_:)``・``line(_:_:_:_:)``・``arc(_:_:_:_:_:_:)`` など。
    ///   ``bezier(_:_:_:_:_:_:_:_:)`` は上のとおり入る)・字・画像・立体は、パスに入らず、描かれない。**種類ごとに 1 度
    ///   だけ報告する。パスには ``beginShape(_:)`` で並べた輪郭だけが入る。奥行きのある頂点も拒否する。効果の要求や塗り直しは、
    ///   ``createShape(_:)`` の中と同じく効かない。
    /// - 中で ``shape(_:_:_:)-(Path,_,_)`` を呼ぶと、描き方 (``fill(_:)-(LinearRGBA)`` や ``stroke(_:)-(LinearRGBA)`` の有無)
    ///   に依らず、そのパスのサブパスが、いまの変換を掛けて 1 回ずつ追加される。非有限の座標になるサブパスは飛ばして、1 度だけ
    ///   報告する。
    /// - **サブパスの並びは、追加された順である。** ``shape(_:_:_:)-(Path,_,_)`` はその場で追加し、開いた
    ///   ``beginShape(_:)`` は ``endShape(_:)`` で追加するので、`beginShape()` の途中で `shape(path)` を呼ぶと、
    ///   `path` のサブパスが先で、外の形が後になる。``Path/point(at:)`` が辿る順もこれである。
    /// - 中で ``createShape(_:)`` を呼べるが、中の形の輪郭は外のパスへ入らない (逆に ``createShape(_:)`` の中の
    ///   ``createPath(_:)`` も同じ)。
    ///
    /// 走っている実行のキャンバスを取れない所 (初期化子の中・後片付けの後など) で呼ぶと、落ちずに空のパスを返し、1 度だけ
    /// 警告する。中身は呼ばれる。
    // shot: 撮れない 道を作る口で、描く結果が無い (描くのは shape(path)。createPath を呼ぶ作例は #2432 (破線) が持つ。参照スケッチ type-and-path は Path(textOutline) で道を作る)
    public func createPath(_ body: () -> Void) -> Path {
        guard let canvas = liveCanvas(.make(returning: "an empty path")) else {
            body()
            return Path()
        }
        return canvas.createPath(body)
    }

    /// パスを描く。
    ///
    /// 塗りと線は、いまの ``fill(_:)-(LinearRGBA)`` と ``stroke(_:)-(LinearRGBA)`` に従う。パスは見た目を持たない。
    /// (`x`, `y`) はパスの原点の位置で、省けば原点 (0, 0) になる。いまの変換が効く。
    ///
    /// **1 つの ``beginShape(_:)`` (``beginContour()`` の穴を含む) から作ったパスは、同じ ``beginShape(_:)`` をその場で描いた
    /// ときと同じ画素になる。** 別々の ``beginShape(_:)`` を 1 つのパスにした場合は、そうならない: 全部を 1 つの形として
    /// 回り数で塗る (逆向きに重なる 2 つの四角は、重なりが抜ける)・塗りを全部描いてから線を描く (重なりの順が変わる)・
    /// 線はサブパスをまとめて 1 つの図形として引く (半透明の線でも、サブパスどうしの線が重なる所は 1 回だけ混ぜる・
    /// SVG や Canvas 2D の 1 本の path と同じ)。3 点に満たないサブパス (線・点) は塗りに使わず、線だけを引く。
    /// ``VertexKind/quads`` など四角の読み方は、四角の継ぎ目の扱いを失い、折れ線の周になる。SVG へ書き出すときも、
    /// 塗りは 1 つの図形、線はサブパスを並べた 1 つの図形になる (点 1 つのサブパスを含むパスと、破線の並びがサブパスごとに
    /// 違うパスは、線をサブパスごとの図形として書く)。
    ///
    /// ``createPath(_:)`` の中で呼ぶと、描かずに、外のパスへサブパスを追加する。
    // shot: 撮れない 道に沿って動く粒は参照スケッチ type-and-path が、破線は #2432 が示す。同じ beginShape との画素の一致は PathTests が見る
    public func shape(_ path: Path, _ x: some ScalarConvertible = 0, _ y: some ScalarConvertible = 0) {
        guard let canvas = liveCanvas() else { return }
        canvas.shape(path, x, y)
    }
}
