// 画素。
extension Sketch {
    /// 描いた結果を画素として読み書きする面。
    ///
    /// 下の例は、同じ橙色の円を 2 つ描いたあと、**左半分の画素だけ**を読んで、成分を
    /// 1 つずつずらして書き戻している (新しい赤は元の緑、新しい緑は元の青、新しい青は元の赤)。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///     noStroke()
    ///     fill(242, 115, 64)
    ///     circle(110, 150, 140)
    ///     circle(290, 150, 140)
    ///
    ///     for y in 0..<pixelHeight {
    ///         for x in 0..<(pixelWidth / 2) {
    ///             let color = pixels[x, y]
    ///             pixels[x, y] = LinearRGBA(
    ///                 premultipliedRed: color.green, green: color.blue, blue: color.red,
    ///                 alpha: color.alpha)
    ///         }
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 同じ橙色の円が 2 つ。右はそのままで、左は成分がずれて青紫になり、下地も緑がかっている | symmetric=y -->
    ///     ![同じ橙色の円が 2 つ。右はそのままで、左は成分がずれて青紫になり、下地も緑がかっている](https://i.gyazo.com/32eba7d571e9ab97bee2bf0a756739bf.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// 書くのも 1 画素ずつである。**書いた画素は、読み直すとその値で返る** — 下の例は
    /// 面の中ほどの帯を 1 画素ずつ書き、右端の画素を読み直して、その色で円を塗っている。
    /// 円は帯の右端と同じ色で出る。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///
    ///     // 面の中ほどの帯を、1 画素ずつ書く。左は青、右は赤橙
    ///     for y in 60..<120 {
    ///         for x in 60..<340 {
    ///             let t = Float(x - 60) / 279
    ///             pixels[x, y] = .display(red: t, green: 0.35, blue: 1 - t)
    ///         }
    ///     }
    ///
    ///     // 書いた画素を読み直し、その色で円を塗る
    ///     let picked = pixels[339, 90]
    ///     noStroke()
    ///     fill(picked)
    ///     circle(200, 200, 100)
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 左が青で右が赤橙の帯が横に渡り、その下の円が帯の右端と同じ赤橙で塗られている -->
    ///     ![左が青で右が赤橙の帯が横に渡り、その下の円が帯の右端と同じ赤橙で塗られている](https://i.gyazo.com/aed62c8b86cef8e115ecd6c049c32f3f.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// ## 送り直しの手順は無い
    ///
    /// 書き換えは、次に描くときに描画先へ自動で戻される。**呼ぶべき送り直しの口が無い**
    /// ので、「書き換えたのに送り直しを呼び忘れて絵が変わらない」という形の不具合が
    /// 起きない。戻すのは書いたフレームだけで、読むだけのフレームは戻さない。
    ///
    /// **描かずに捨てたフレームで書いた分は戻らない** — 描き切りに失敗したフレームと、描き場所で
    /// `endDraw()` を閉じ忘れたフレームである。置いた図形と同じく、そのフレームごと捨てる。
    /// 閉じ忘れたフレームは本体の次のフレームの頭で捨てるので、その後に読めば捨てる前の絵が
    /// 返る。捨てる前 (同じ本体のフレームの中) に途中で画素を読んだ (描き切った) ときは、それより
    /// 前に書いた分は既に描画先へ載っていて残る。
    /// `setup()` で書いた分は最初のフレームへ持ち越すので、その描き切りが失敗すれば、そこで
    /// 置いた図形と一緒に捨てる。
    ///
    /// **止まっている間のコールバックで書いた分は、配った直後に描画先へ戻す** (窓・書き出し・
    /// 観測が、書いた絵をその場で受け取るため)。後で描くフレームの描き切りが失敗しても消えず、
    /// 捨てるのは、そのフレームへ持ち越した図形・絵・背景と、そのフレームで置いたものだけである。
    /// 同じコールバックで ``redraw()`` を呼んだ
    /// ときだけは、そのフレームの頭で戻すので、描き切りが失敗すれば置いた図形と一緒に捨てる。
    ///
    /// ## 読む値と書く値は同じ表現
    ///
    /// どちらも ``LinearRGBA`` — 線形・アルファ乗算済みの作業空間の値である。
    /// 変換が挟まらないので `pixels[x, y] = pixels[x, y]` は絵を変えない。
    /// 半透明の画素でも同じで、読んで書き戻すだけで色が沈むことはない。
    ///
    /// 下の例は、半透明の面に同じ色の円を 2 つ描き、**右半分だけ**を読んだ値のまま書き戻している。
    /// 書き戻した右の円も、書き戻さない左の円と同じ色で出る。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31, 128)
    ///     noStroke()
    ///     fill(242, 115, 64, 128)
    ///     circle(110, 150, 140)
    ///     circle(290, 130, 100)
    ///
    ///     for y in 0..<pixelHeight {
    ///         for x in (pixelWidth / 2)..<pixelWidth {
    ///             pixels[x, y] = pixels[x, y]
    ///         }
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 半透明の面に同じ色の円が 2 つ。右の円は読んで書き戻したものだが、左の円と同じ色のまま -->
    ///     ![半透明の面に同じ色の円が 2 つ。右の円は読んで書き戻したものだが、左の円と同じ色のまま](https://i.gyazo.com/2eaeedbaffab1ecd39e50e2399a10c2c.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// ## いつの絵が読めるか
    ///
    /// **そのフレームでそこまでに描いたもの**が読める。触れた時点で溜めていた図形が
    /// 描き切られ、GPU の完了を待つ。読んだあとに描いた図形も、次に触れたときに
    /// 描き切られる。描かずに読み続けるなら待つのは 1 度きりなので、何画素読んでも
    /// 待ち時間は増えない。待つ時点を自分で選びたいときは ``loadPixels()`` を先に呼ぶ。
    ///
    /// **読む・書くところが、そのフレームの区切りになる。** 区切りでは、それまでに置いた図形を
    /// 描くのと一緒に、それまでに頼んだ計算 (``compute(_:over:reads:writes:)``) と、数の並び
    /// (``Numbers``) や画像へ書いた値の届けも、その時点で流れる。だから区切りより前に置いたもの・
    /// 頼んだものには、後から変えたものが効かない:
    ///
    /// - 区切りより前に置いた図形は、区切りの後に置いた立体の影 (``shadows(_:)``)・区切りの後に頼んだ
    ///   計算・区切りの後に書いた値を受けない
    /// - 区切りより前に頼んだ計算は、区切りの時点の入力で流れる。区切りの後にその入力の並びへ書いても、
    ///   計算は読み直さない (区切らなければ、書いた後の値から計算する)
    ///
    /// それ以外の、区切りより後に置いたものは、区切らずに描いたときと同じに描かれる — 区切りより前に
    /// 置いた立体の影も受け、区切りより前に頼んだ計算の結果と書いた値も読む。後から変えるものを読む
    /// 図形と計算は、読む・書くより後に置く・頼む。
    ///
    /// **読むのと描くのを交互に繰り返すと、読むたびに待つ。** 1 画素読んでは図形を
    /// 1 つ置く、を画面の広さだけ回すと、その回数だけ GPU を待つ。先に読みたい画素を
    /// まとめて読んでから描く。
    ///
    /// **取ったフレームの中で使い切る。** 返るのは描画先の写しへの窓で、写しは次に
    /// 画素を読むときに描き直される。プロパティに取っておいて次のフレームで読むと
    /// 古い絵が読め、書くと GPU が写しを書いている途中に触ることになる。次のフレーム
    /// では `pixels` をもう一度取る。
    ///
    /// ## 索引は実際に刻んでいる画素
    ///
    /// 大きさは ``pixelWidth`` / ``pixelHeight`` で、細かさ
    /// (``SketchSettings/pixelDensity``) を下げているときは ``width`` / ``height``
    /// より小さい。**読み書きするのは拡大より手前の絵**なので、ここで書いた値も
    /// 拡大を通ってから出て行く。
    // shot: 1 snippet=0617ccbc
    // shot: 2 snippet=ab94a2c3
    // shot: 3 snippet=f1c90989
    public var pixels: Pixels { canvas.pixels }

    /// 溜めている図形を描き切り、画素を読める状態にする。
    ///
    /// ``pixels`` も ``get(_:_:)`` も ``set(_:_:_:)`` も必要なら自分で呼ぶので、
    /// **省いても結果は変わらない**。待つ時点を選びたいときに使う。
    ///
    /// **呼んだところが、そのフレームの区切りになる** (読む口がどれも同じ区切りを入れる)。区切りより
    /// 後に置いたものは区切らずに描いたときと同じに描かれるが、区切りより前に置いたものには、区切りの
    /// 後に置いた立体の影・頼んだ計算・書いた値が届かない (``pixels`` の「いつの絵が読めるか」)。
    ///
    /// 下の 2 枚は、影を受けるだけの床を置いてから球を置く同じ場面で、違うのは床の後に
    /// `loadPixels()` を呼ぶかだけである。呼ぶと床はそこで描き切られるので、**そのあとに置いた
    /// 球の影を受けない**。呼ばなければ、床の左奥に影が落ちる。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///     camera(200, -70, 320, 200, 200, 0, 0, 1, 0)
    ///     lights()
    ///     shadows(true)
    ///     noStroke()
    ///     castShadow(false)
    ///     fill(191, 191, 199)
    ///     push()
    ///     translate(200, 250, -20)
    ///     box(400, 8, 300)
    ///     pop()
    ///     // 床の後に loadPixels() を呼ばない
    ///     castShadow(true)
    ///     fill(242, 115, 64)
    ///     push()
    ///     translate(180, 120, 20)
    ///     sphere(75)
    ///     pop()
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 灰色の床の上に橙色の球が浮かび、床の左奥に球の影が落ちている -->
    ///     ![灰色の床の上に橙色の球が浮かび、床の左奥に球の影が落ちている](https://i.gyazo.com/6ad2eba7dd78eb4ade8ed2e6fd2318b9.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///     camera(200, -70, 320, 200, 200, 0, 0, 1, 0)
    ///     lights()
    ///     shadows(true)
    ///     noStroke()
    ///     castShadow(false)
    ///     fill(191, 191, 199)
    ///     push()
    ///     translate(200, 250, -20)
    ///     box(400, 8, 300)
    ///     pop()
    ///     loadPixels()   // 床はここで描き切られる
    ///     castShadow(true)
    ///     fill(242, 115, 64)
    ///     push()
    ///     translate(180, 120, 20)
    ///     sphere(75)
    ///     pop()
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 上と同じ場面だが、床に球の影が落ちておらず、床は一様に明るい -->
    ///     ![上と同じ場面だが、床に球の影が落ちておらず、床は一様に明るい](https://i.gyazo.com/b68b982ab4bea4d84df2aa49e761b609.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    // shot: 1 snippet=1276c674
    // shot: 2 snippet=2bff752d
    public func loadPixels() { canvas.loadPixels() }

    /// 1 画素の色。原点は左上。範囲の外は透明を返す。索引は ``pixels`` と同じ。
    ///
    /// **返す値は線形・アルファ乗算済みの ``LinearRGBA`` である** ([ADR-0011] 決定 4)。塗りの色
    /// (``fill(_:)``) や ``set(_:_:_:)`` が受けるのも同じ表現なので、読んだ値を
    /// そのまま渡せば、半透明の画素でも同じ色が出る。0–255 の乗算していない数として読むときは
    /// ``red(_:)`` / ``green(_:)`` / ``blue(_:)`` / ``alpha(_:)`` を通す。
    ///
    /// [ADR-0011]: https://github.com/mokume-metal/mokume/blob/main/docs/decisions/0011-color-model.md
    ///
    /// **そのフレームでそこまでに描いたもの**が読める。下の例は先に描いた円の中から
    /// 色を 1 つ読み、その色で別の図形を塗っている — 2 つは同じ色で出る。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///     noStroke()
    ///     fill(242, 115, 64)
    ///     circle(110, 100, 140)
    ///     let picked = get(110, 100)   // 円の中の 1 画素
    ///     fill(picked)
    ///     rect(230, 160, 130, 100)
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 左上に橙色の円、右下に同じ橙色で塗られた四角 -->
    ///     ![左上に橙色の円、右下に同じ橙色で塗られた四角](https://i.gyazo.com/9b9db97c9ea5d54f29440203cc7edfa9.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    // shot: 1 snippet=6fc06851
    public func get(_ x: Int, _ y: Int) -> LinearRGBA { canvas.get(x, y) }

    /// 1 画素の色を書き換える。範囲の外は何もしない。
    ///
    /// **書いた画素だけが変わる。** 図形を描く口と違って塗りも線も見ないので、
    /// 下の例では書いた範囲の外が下地のまま残る。
    ///
    /// 色は検めずに面へ移す。数でない成分・無限の成分もそのまま書き (図形を描く経路が面へ
    /// 移すときと同じ)、有限の成分は面が表せる ±65504 で止まる。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     ```swift
    ///     background(23, 26, 31)
    ///     for y in 60..<240 {
    ///         for x in 100..<300 {
    ///             if (x + y) % 12 < 6 {
    ///                 set(x, y, color(242, 217, 89))
    ///             }
    ///         }
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 黄色い斜めの縞が、四角い範囲の中にだけ並んでいる -->
    ///     ![黄色い斜めの縞が、四角い範囲の中にだけ並んでいる](https://i.gyazo.com/b3cdd5a675acfc0ea675176f3e769328.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    // shot: 1 snippet=e62332bb
    public func set(_ x: Int, _ y: Int, _ color: LinearRGBA) { canvas.set(x, y, color) }
}
