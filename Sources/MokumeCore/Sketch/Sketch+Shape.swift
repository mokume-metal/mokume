// 保持した形。
extension Sketch {
    /// 形を組み立てて保持する。**毎フレーム組み立て直さずに済む。**
    ///
    /// 組み立てるのは `setup()` で 1 度だけ。`draw()` では、保持した形を ``shape(_:_:_:)`` で
    /// 置くだけでよい。下は 1 枚の葉を 1 度だけ組み立てて、3 行 × 6 列に置いたもの —
    /// 18 枚どれも、同じ形から出ている (置くときに回しているので、傾きは 1 枚ごとに違う)。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     <!-- example: 文脈 var leaf: Shape! -->
    ///     ```swift
    ///     func setup() {
    ///         leaf = createShape {
    ///             noStroke()
    ///             fill(102, 204, 89)
    ///             beginShape()
    ///             vertex(0, -20)
    ///             bezierVertex(14, -14, 14, 14, 0, 20)
    ///             bezierVertex(-14, 14, -14, -14, 0, -20)
    ///             endShape(.close)
    ///         }
    ///     }
    ///
    ///     func draw() {
    ///         background(23, 26, 31)
    ///         for i in 0..<18 {
    ///             push()
    ///             translate(45 + Float(i % 6) * 62, 60 + Float(i / 6) * 90)
    ///             rotate(Float(i) * 0.35)
    ///             shape(leaf)
    ///             pop()
    ///         }
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 同じ緑の葉が 3 行 × 6 列に並び、1 枚ずつ少しずつ傾きが違う -->
    ///     ![同じ緑の葉が 3 行 × 6 列に並び、1 枚ずつ少しずつ傾きが違う](https://i.gyazo.com/67b35ba9702070f00b028cf108d00bbb.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// ## 色は形の中に焼き付く
    ///
    /// 中で呼んだ ``fill(_:)`` や ``stroke(_:)`` は、組み立てた時点で頂点の色になる。
    /// **だから塗りや輪郭は形の中で決める** — 置くときに外から ``fill(_:)`` を変えても
    /// 形の色は変わらない。組み立てるコードを読めば何色になるかが分かり、置く側の
    /// コードを読んでも分からない、という形にしてある。
    ///
    /// 下は、置く側で ``fill(_:)`` を橙・水色・黄と替えながら、そのつど円と葉を並べたもの。
    /// 円は外の塗りの色に変わるが、葉は組み立てたときの緑のまま出る。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     <!-- example: 文脈 var leaf: Shape! -->
    ///     ```swift
    ///     func setup() {
    ///         leaf = createShape {
    ///             noStroke()
    ///             fill(102, 204, 89)
    ///             beginShape()
    ///             vertex(0, -20)
    ///             bezierVertex(14, -14, 14, 14, 0, 20)
    ///             bezierVertex(-14, 14, -14, -14, 0, -20)
    ///             endShape(.close)
    ///         }
    ///     }
    ///
    ///     func draw() {
    ///         background(23, 26, 31)
    ///         noStroke()
    ///         fill(242, 115, 64)
    ///         circle(70, 120, 60)
    ///         shape(leaf, 70, 200)
    ///         fill(89, 191, 242)
    ///         circle(200, 120, 60)
    ///         shape(leaf, 200, 200)
    ///         fill(242, 217, 89)
    ///         circle(330, 120, 60)
    ///         shape(leaf, 330, 200)
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 上に橙・水色・黄の円が 1 つずつ、その下に同じ緑の葉が 1 枚ずつ並んでいる -->
    ///     ![上に橙・水色・黄の円が 1 つずつ、その下に同じ緑の葉が 1 枚ずつ並んでいる](https://i.gyazo.com/9acd2e3816ba96b86a54a1fb97e4622a.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// **焼き付くのは色だけではない。** 組み立ての間に効いていた ``shader(_:)`` と、
    /// そのとき渡していた値・面・数の並びも形が持ち歩く。置く前に ``resetShader()``
    /// しても、別の断片へ切り替えても、形は記録した塗りで出る。線の太さ
    /// (``strokeWeight(_:)``) も記録したものが残るが、立体の線は**置いたときの画面の
    /// 画素**で出る — 回して置いても、奥や手前へ置いても、拡大して置いても、その場で
    /// 描いた線と同じ太さと位置になる。
    ///
    /// 置く場所は別で、``translate(_:_:)`` や ``rotate(_:)`` は置くときに効く。
    /// 色は形のもので、場所は置き方のもの、という切り分けである。
    ///
    /// ## 中で触った設定は外へ残らない
    ///
    /// 組み立ての中で呼んだ ``fill(_:)`` ・ ``stroke(_:)`` ・ ``blendMode(_:)`` ・
    /// ``shader(_:)`` ・ ``numbers(_:)`` ・ `texture()` などの描き方は、抜けると組み立てる前の
    /// 状態へ戻る。曲線の細かさと張り (``curveDetail(_:)`` ・ ``curveTightness(_:)``) も同じである。
    /// 形に焼き付くだけで、そのあとに描くものには効かない — 中で ``curveDetail(_:)`` を下げて
    /// 組んだ形は粗く刻まれ、外の曲線は元の細かさのまま出る。
    ///
    /// 揺らぎの種と細かさ (``noiseSeed(_:)`` ・ ``noiseDetail(_:_:)``) も抜けると戻るが、**形に
    /// 焼き付くのは、中で ``noise(_:_:_:)`` が返した値 (それで決めた位置や色) だけである。**
    /// 断片の `mokume_noise` は置いたときの種で引くので、中で種を書いて断片で塗った形も、置いた
    /// ときの種で出る。中で書き換えても、組み立ての前に置いたものは置いた時点の種のまま描かれ、
    /// 形も中で描いたものを持つ (いつ書き換えてもよい)。
    ///
    /// 乱数の種 (``randomSeed(_:)``) も抜けると戻る。**中で種を書くと、そこから抜けるまでは中で決めた
    /// 列で引き、抜けた後の列は最初に書く直前の状態から続く。** 種を書く前に中で ``random()`` を引いた
    /// 分と、種を書かずに引いた分は、外で引いたのと同じく 1 本の列を進める。描き場所 (``createGraphics(_:_:)``) の
    /// `createShape { }` でも、``Canvas`` を直に作った面 (``Canvas/init(target:gpu:)``) とそこから作った
    /// 描き場所の `createShape { }` でも、`setup()` と ``draw()`` のどちらで組み立てても同じである。
    /// スケッチの口で書いた揺らぎの種と細かさも、どの面で組み立てても同じく戻る。
    ///
    /// ```swift
    /// randomSeed(1)
    /// let petals = createShape {
    ///     randomSeed(42)
    ///     circle(random(100), 50, 10)
    /// }
    /// let next = random()  // 種 1 の列の 1 つ目。中で書いた種 42 の続きではない
    /// ```
    ///
    /// 外でも同じ種を使い続けたいなら、組み立てた後で ``randomSeed(_:)`` を書き直す。
    ///
    /// **``push()`` で積んだのと同じにはならない。** ``push()`` は断片と数の並びを
    /// 積まないが、組み立ては 2 つとも戻す。戻し方も積み降ろしに頼らないので、
    /// `setup()` で組み立てても同じように戻る。
    ///
    /// ## 中の積み降ろしは、中で閉じる
    ///
    /// 組み立ての中の ``push()`` / ``pop()`` は**組み立ての中だけで効く**。`setup()` で
    /// 組み立てても効き方は変わらず、中で積んだまま抜けても、外の ``pop()`` がそれを
    /// 拾うことはない。中の ``pop()`` も、外で積んだ段には届かない。
    ///
    /// ## 中で呼んでも効かない口
    ///
    /// 形に焼き付く先が無い口は、組み立ての中では 1 度注意して何もしない。**`draw()` の中で
    /// 組み立てても `setup()` で組み立てても同じ**で、組み立ての後にも残らない。
    ///
    /// - ``background(_:)-(LinearRGBA)`` (``background(_:)-(Surroundings)`` も): 塗り直しは面全体を描き直すことで、
    ///   形には持たせられない。組み立ての前か後で呼ぶ
    /// - 画素の読み書き (``get(_:_:)``・``set(_:_:_:)``・``pixels``・``loadPixels()``): 組み立てた
    ///   ものはまだ描いていないので読めない。``get(_:_:)`` は透明を返し、``pixels`` は読み込み
    ///   直さずにいまの写しを返す (このフレームでまだ読んでいなければ、前に読んだときの絵)。
    ///   どちらも状態は変えない。書き込みは書かれない
    /// - シーンの記述 (視点と投影・``clip(_:_:_:_:)``・``effects(_:)``・光・``surroundings(_:)``・
    ///   影・材質・粒・`compute()`): 形が持ち歩けるのは描き方と変換だけで、
    ///   どこへ置くか分からない形には光も視点も持たせられない。切り抜きは描画先の座標で効く。
    ///   組み立ての前か後で書く
    /// - ``exposure(_:)``・``toneMapping(_:)``: 面全体の明るさを決めるもので、形には焼き付かない
    ///
    /// 同じフレームで先に置いた描き場所 (``createGraphics(_:_:)``) の画素も、読み込み直しが要る
    /// なら組み立ての中では読み書きしない (読み込むと、置いた側のこの組み立てを描き切らせうる)。
    ///
    /// ## 中で描き換えても、形もフレームも崩れない
    ///
    /// 次のことは組み立ての中でしてよい。形は中で描いたものを持ち、中で描いたものはそのフレームに
    /// 出ず、組み立ての前に置いたものは置いた時点のまま描かれる。
    ///
    /// - 揺らぎの設定 (``noiseSeed(_:)``・``noiseDetail(_:_:)``) を書き換える。組み立ての前に置いた
    ///   ものは置いた時点の設定で、中で置いたものは中の設定で描かれ、抜けると外の設定へ戻る
    /// - 同じフレームで先に置いた描き場所を、中で描き換える (`beginDraw()` から `endDraw()` まで)。
    ///   先に置いた所は描き換える前の絵で出る。形の中で置いた描き場所は、形を置いたときの絵を読む
    /// - 描き場所の `createShape { }` の中で、その描き場所のフレームを閉じる (`endDraw()` を呼ぶ・
    ///   組み立ての中で開いた `draw { }` を抜ける)。そこでは閉じず (1 度注意する)、組み立ての出口
    ///   (入れ子なら一番外) でフレームを閉じる。閉じた後に描いたものも形に入る。**出口までは、その
    ///   描き場所はまだ描いている扱いである** — 組み立ての残りで `beginDraw()` を呼んでも、開いた
    ///   フレームが続いていると注意して何もせず、別の面へ置く (`image(pg)` など) と前の絵を読む
    ///
    /// **組み立ての中でフレームが描き切られるか捨てられると、形は空になる** (1 度注意する)。次の 2 つが
    /// それに当たる。どちらも組み立ての前か後で行う。
    ///
    /// - 1 フレームに「置く → 描き換える」を 4 回より多く繰り返し、越えた分の描き換えが組み立ての中に
    ///   来る (置いた側は描き換える前の絵の写しを 4 枚まで持ち、越えるか写しを用意できないと描き切って
    ///   守る・``createGraphics(_:_:)``)。描き切りまでに組み立てたぶんは、形にならずにそのフレームへ
    ///   描かれる
    /// - フレームの外の描き場所で始めた `createShape { }` の中で、その描き場所のフレームを始める
    ///   (`beginDraw()` を呼ぶか `draw { }` を開く)。**それより前にこの組み立てで描いたものがあれば**、
    ///   フレームの外で置いたものとして描かれずに捨てられ、形は空になる (何も描いていなければ空に
    ///   ならず、閉じるのは上のとおり出口になる)
    ///
    /// ## 座標は形自身のもの
    ///
    /// 組み立ての間、変換は畳まれている。どこで組み立てても同じ形になり、
    /// ``shape(_:_:_:)`` の与える位置がそのまま形の原点になる。
    ///
    /// **畳まれるのは組み立てに入る時点までで、中で書いた変換は形に焼き付く。**
    /// 下のように 1 つの形の中で置き場所を書き分けられ、`setup()` で組み立てても
    /// `draw()` で組み立てても同じ形になる。
    ///
    /// <!-- example: 文脈 var leaf: Shape! -->
    /// ```swift
    /// let cluster = Shape.group(
    ///     (0..<9).map { index in
    ///         createShape {
    ///             push()
    ///             translate(Float(index % 3) * 46, Float(index / 3) * 46)
    ///             rotate(Float(index) * 0.4)
    ///             shape(leaf)
    ///             pop()
    ///         }
    ///     })
    /// ```
    ///
    /// ## 組にしても描く回数は増えない
    ///
    /// ``Shape/group(_:)`` と `+` は形を**1 本の頂点の並びへ畳む**。子の一覧を持って
    /// 1 つずつ描く作りではないので、「保持にしたのに速くならない」が起きない。
    // shot: 1 snippet=2caf9b37
    // shot: 2 snippet=77b00113
    public func createShape(_ body: () -> Void) -> Shape { canvas.createShape(body) }

    /// 保持した形を、**置き場所ぶんだけまとめて置く**。
    ///
    /// 同じ形をたくさん置くときは、これがいちばん速い。形の頂点は 1 度しか置かれず、
    /// 置き場所の数だけ描き足される — 1 万個置いても**描く回数は 1 回**になる。
    ///
    /// ```swift
    /// let grain = createShape { box(6) }
    /// var places: [Placement] = []
    /// for _ in 0..<5000 {
    ///     places.append(
    ///         Placement(
    ///             x: random(width), y: random(height),
    ///             rotation: SIMD3(0, random(2 * Float.pi), 0)))
    /// }
    /// shape(grain, at: places)
    /// ```
    ///
    /// **1 つずつ置いたときと同じ絵になる。** `push()` / `translate()` / `pop()` の
    /// 繰り返しで書いても、まとめて渡しても、経路は 1 本しかない。
    ///
    /// ``Placement/fill`` を渡すと、その置き場所の色に**掛かる** (渡さなければ何も
    /// 掛からない)。
    ///
    /// 下は、白で記録した葉を、位置・回転・大きさの違う 5 か所に置いたもの。上の段は
    /// まとめて渡し、中の段は `push()` / `translate()` / `rotate()` / `scale()` / `pop()` で
    /// 1 つずつ置いている。2 つの段は同じ絵になる。下の段は、中の段と同じ置き場所に ``Placement/fill``
    /// を渡したもので、白に掛かって色がつく。5 つ目だけは塗りを渡していないので、記録した白のまま出る。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     <!-- example: 文脈 var leaf: Shape! -->
    ///     ```swift
    ///     func setup() {
    ///         leaf = createShape {
    ///             noStroke()
    ///             fill(255)
    ///             beginShape()
    ///             vertex(0, -20)
    ///             bezierVertex(14, -14, 14, 14, 0, 20)
    ///             bezierVertex(-14, 14, -14, -14, 0, -20)
    ///             endShape(.close)
    ///         }
    ///     }
    ///
    ///     func draw() {
    ///         background(23, 26, 31)
    ///         let colors: [LinearRGBA?] = [
    ///             .display(red: 0.95, green: 0.45, blue: 0.25),
    ///             .display(red: 0.35, green: 0.75, blue: 0.95),
    ///             .display(red: 0.95, green: 0.85, blue: 0.35),
    ///             .display(red: 0.40, green: 0.80, blue: 0.35),
    ///             nil,
    ///         ]
    ///         var plain: [Placement] = []
    ///         var tinted: [Placement] = []
    ///         for i in 0..<5 {
    ///             let (x, size, turn) = (50 + Float(i) * 75, 0.8 + Float(i) * 0.2, Float(i) * 0.5)
    ///             plain.append(Placement(x: x, y: 50, scale: size, rotation: SIMD3(0, 0, turn)))
    ///             tinted.append(Placement(x: x, y: 250, scale: size, rotation: SIMD3(0, 0, turn), fill: colors[i]))
    ///         }
    ///         shape(leaf, at: plain)          // 上の段: まとめて
    ///         shape(leaf, at: tinted)         // 下の段: 塗りも渡す
    ///
    ///         for i in 0..<5 {                // 中の段: 1 つずつ
    ///             push()
    ///             translate(50 + Float(i) * 75, 150)
    ///             rotate(Float(i) * 0.5)
    ///             scale(0.8 + Float(i) * 0.2, 0.8 + Float(i) * 0.2)
    ///             shape(leaf)
    ///             pop()
    ///         }
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 白い葉が 5 枚ずつ 3 段。右へ行くほど大きく傾いていて、上と中の段は同じ。下の段は左から橙・水色・黄・緑・白に染まっている -->
    ///     ![白い葉が 5 枚ずつ 3 段。右へ行くほど大きく傾いていて、上と中の段は同じ。下の段は左から橙・水色・黄・緑・白に染まっている](https://i.gyazo.com/fc31d8f69860247f0699626a3de238f6.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    // shot: 1 snippet=276142f3
    public func shape(_ shape: Shape, at placements: [Placement]) {
        canvas.shape(shape, at: placements)
    }

    /// 保持した形を置く。
    ///
    /// 色は形が持っているものが使われ、置く場所といまの変換が効く。
    ///
    /// (`x`, `y`) は形の原点の置き場所で、省けば原点 (0, 0) になる。上の段は、(`x`, `y`) だけを
    /// 80・190・310 と動かして置いたもの。置く側の ``fill(_:)`` は橙だが、葉の色は組み立てたときの
    /// 緑のままである (橙で塗られるのは、間に置いた円だけ)。下の段は、先に ``translate(_:_:)`` ・
    /// ``rotate(_:)`` ・ ``scale(_:_:)`` で原点を動かし、傾けて大きくしてから、位置を省いて置いたもの —
    /// いまの変換がそのまま効く。
    ///
    /// @Row {
    ///   @Column(size: 3) {
    ///     <!-- example: 文脈 var leaf: Shape! -->
    ///     ```swift
    ///     func setup() {
    ///         leaf = createShape {
    ///             noStroke()
    ///             fill(102, 204, 89)
    ///             beginShape()
    ///             vertex(0, -20)
    ///             bezierVertex(14, -14, 14, 14, 0, 20)
    ///             bezierVertex(-14, 14, -14, -14, 0, -20)
    ///             endShape(.close)
    ///         }
    ///     }
    ///
    ///     func draw() {
    ///         background(23, 26, 31)
    ///         noStroke()
    ///         fill(242, 115, 64)              // 置く側の塗り。葉の色には効かない
    ///         circle(200, 140, 30)
    ///         shape(leaf, 80, 80)
    ///         shape(leaf, 190, 80)
    ///         shape(leaf, 310, 80)
    ///
    ///         translate(150, 220)
    ///         rotate(Float.pi / 4)
    ///         scale(2, 2)
    ///         shape(leaf)                     // 位置を省けば、動かした原点に置かれる
    ///     }
    ///     ```
    ///   }
    ///   @Column {
    ///     <!-- shot: 上の段に緑の葉が 3 枚、間隔を変えて並ぶ。その下の中央に橙の小さな円、さらに下の左寄りに、斜めに傾いた大きな緑の葉が 1 枚 -->
    ///     ![上の段に緑の葉が 3 枚、間隔を変えて並ぶ。その下の中央に橙の小さな円、さらに下の左寄りに、斜めに傾いた大きな緑の葉が 1 枚](https://i.gyazo.com/c95576c066d2deb5aaa6c2d90003230d.png)
    ///     <!-- /shot -->
    ///   }
    /// }
    ///
    /// **たくさん置くときは shape(_:at:) を使う。** こちらは 1 回ごとに頂点を
    /// 置き直すので、置く数だけ描く回数が増える。
    // shot: 1 snippet=73a8868f
    public func shape(_ shape: Shape, _ x: some ScalarConvertible = 0, _ y: some ScalarConvertible = 0) {
        let (x, y) = (x.asFloat, y.asFloat)
        canvas.shape(shape, x, y)
    }
}
