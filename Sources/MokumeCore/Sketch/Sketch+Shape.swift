// 保持した形。
extension Sketch {
    /// 形を組み立てて保持する。**毎フレーム組み立て直さずに済む。**
    ///
    /// <!-- example: 文脈 var leaf: Shape! -->
    /// ```swift
    /// func setup() {
    ///     leaf = createShape {
    ///         noStroke()
    ///         fill(102, 204, 89)
    ///         beginShape()
    ///         vertex(0, -20)
    ///         bezierVertex(14, -14, 14, 14, 0, 20)
    ///         bezierVertex(-14, 14, -14, -14, 0, -20)
    ///         endShape(.close)
    ///     }
    /// }
    ///
    /// func draw() {
    ///     for i in 0..<2000 { shape(leaf, Float(i % 50) * 8 + 10, Float(i / 50) * 8 + 10) }
    /// }
    /// ```
    ///
    /// ## 色は形の中に焼き付く
    ///
    /// 中で呼んだ ``fill(_:)`` や ``stroke(_:)`` は、組み立てた時点で頂点の色になる。
    /// **だから塗りや輪郭は形の中で決める** — 置くときに外から ``fill(_:)`` を変えても
    /// 形の色は変わらない。組み立てるコードを読めば何色になるかが分かり、置く側の
    /// コードを読んでも分からない、という形にしてある。
    ///
    /// **焼き付くのは色だけではない。** 組み立ての間に効いていた ``shader(_:)`` と、
    /// そのとき渡していた値・面・数の並びも形が持ち歩く。置く前に ``resetShader()``
    /// しても、別の断片へ切り替えても、形は記録した塗りで出る。線の太さ
    /// (``strokeWeight(_:)``) も記録したものが残るが、立体の線は**置いたときの画面の
    /// 画素**で出る — 回して置いても、奥や手前へ置いても、拡大して置いても、その場で
    /// 描いた線と同じ太さと位置になる。
    ///
    /// 置く場所は別で、``translate(_:_:)`` や ``rotate(_:)`` は置くときに効く。
    /// 色は形のもので、場所は置き方のもの、という切り分けである。
    ///
    /// ## 中で触った設定は外へ残らない
    ///
    /// 組み立ての中で呼んだ ``fill(_:)`` ・ ``stroke(_:)`` ・ ``blendMode(_:)`` ・
    /// ``shader(_:)`` ・ ``numbers(_:)`` ・ `texture()` などの描き方は、抜けると組み立てる前の
    /// 状態へ戻る。曲線の細かさと張り (``curveDetail(_:)`` ・ ``curveTightness(_:)``) も同じである。
    /// 形に焼き付くだけで、そのあとに描くものには効かない — 中で ``curveDetail(_:)`` を下げて
    /// 組んだ形は粗く刻まれ、外の曲線は元の細かさのまま出る。
    ///
    /// 揺らぎの種と細かさ (``noiseSeed(_:)`` ・ ``noiseDetail(_:_:)``) も抜けると戻るが、**形に
    /// 焼き付くのは、中で ``noise(_:_:_:)`` が返した値 (それで決めた位置や色) だけである。**
    /// 断片の `mokume_noise` は置いたときの種で引くので、中で種を書いて断片で塗った形も、置いた
    /// ときの種で出る。中で書き換えても、組み立ての前に置いたものは置いた時点の種のまま描かれ、
    /// 形も中で描いたものを持つ (いつ書き換えてもよい)。
    ///
    /// 乱数の種 (``randomSeed(_:)``) も抜けると戻る。**中で種を書くと、そこから抜けるまでは中で決めた
    /// 列で引き、抜けた後の列は最初に書く直前の状態から続く。** 種を書く前に中で ``random()`` を引いた
    /// 分と、種を書かずに引いた分は、外で引いたのと同じく 1 本の列を進める。描き場所 (``createGraphics(_:_:)``) の
    /// `createShape { }` でも、``Canvas`` を直に作った面 (``Canvas/init(target:gpu:)``) とそこから作った
    /// 描き場所の `createShape { }` でも、`setup()` と ``draw()`` のどちらで組み立てても同じである。
    /// スケッチの口で書いた揺らぎの種と細かさも、どの面で組み立てても同じく戻る。
    ///
    /// ```swift
    /// randomSeed(1)
    /// let petals = createShape {
    ///     randomSeed(42)
    ///     circle(random(100), 50, 10)
    /// }
    /// let next = random()  // 種 1 の列の 1 つ目。中で書いた種 42 の続きではない
    /// ```
    ///
    /// 外でも同じ種を使い続けたいなら、組み立てた後で ``randomSeed(_:)`` を書き直す。
    ///
    /// **``push()`` で積んだのと同じにはならない。** ``push()`` は断片と数の並びを
    /// 積まないが、組み立ては 2 つとも戻す。戻し方も積み降ろしに頼らないので、
    /// `setup()` で組み立てても同じように戻る。
    ///
    /// ## 中の積み降ろしは、中で閉じる
    ///
    /// 組み立ての中の ``push()`` / ``pop()`` は**組み立ての中だけで効く**。`setup()` で
    /// 組み立てても効き方は変わらず、中で積んだまま抜けても、外の ``pop()`` がそれを
    /// 拾うことはない。中の ``pop()`` も、外で積んだ段には届かない。
    ///
    /// ## 中で呼んでも効かない口
    ///
    /// 形に焼き付く先が無い口は、組み立ての中では 1 度注意して何もしない。**`draw()` の中で
    /// 組み立てても `setup()` で組み立てても同じ**で、組み立ての後にも残らない。
    ///
    /// - ``background(_:)-(LinearRGBA)`` (``background(_:)-(Surroundings)`` も): 塗り直しは面全体を描き直すことで、
    ///   形には持たせられない。組み立ての前か後で呼ぶ
    /// - 画素の読み書き (``get(_:_:)``・``set(_:_:_:)``・``pixels``・``loadPixels()``): 組み立てた
    ///   ものはまだ描いていないので読めない。``get(_:_:)`` は透明を返し、``pixels`` は読み込み
    ///   直さずにいまの写しを返す (このフレームでまだ読んでいなければ、前に読んだときの絵)。
    ///   どちらも状態は変えない。書き込みは書かれない
    /// - シーンの記述 (視点と投影・``clip(_:_:_:_:)``・``effects(_:)``・光・``surroundings(_:)``・
    ///   影・材質・粒・`compute()`): 形が持ち歩けるのは描き方と変換だけで、
    ///   どこへ置くか分からない形には光も視点も持たせられない。切り抜きは描画先の座標で効く。
    ///   組み立ての前か後で書く
    /// - ``exposure(_:)``・``toneMapping(_:)``: 面全体の明るさを決めるもので、形には焼き付かない
    ///
    /// 同じフレームで先に置いた描き場所 (``createGraphics(_:_:)``) の画素も、読み込み直しが要る
    /// なら組み立ての中では読み書きしない (読み込むと、置いた側のこの組み立てを描き切らせうる)。
    ///
    /// ## 中で描き換えても、形もフレームも崩れない
    ///
    /// 次のことは組み立ての中でしてよい。形は中で描いたものを持ち、中で描いたものはそのフレームに
    /// 出ず、組み立ての前に置いたものは置いた時点のまま描かれる。
    ///
    /// - 揺らぎの設定 (``noiseSeed(_:)``・``noiseDetail(_:_:)``) を書き換える。組み立ての前に置いた
    ///   ものは置いた時点の設定で、中で置いたものは中の設定で描かれ、抜けると外の設定へ戻る
    /// - 同じフレームで先に置いた描き場所を、中で描き換える (`beginDraw()` から `endDraw()` まで)。
    ///   先に置いた所は描き換える前の絵で出る。形の中で置いた描き場所は、形を置いたときの絵を読む
    /// - 描き場所の `createShape { }` の中で、その描き場所の `endDraw()` を呼ぶ。そこでは閉じず
    ///   (1 度注意する)、組み立ての出口 (入れ子なら一番外) でフレームを閉じる。呼んだ後に描いた
    ///   ものも形に入る
    ///
    /// **組み立ての中でフレームが描き切られると、形は空になる** (1 度注意する)。次の 2 つがそれに
    /// 当たる。どちらも組み立ての前か後で行う。
    ///
    /// - 1 フレームに「置く → 描き換える」を 4 回より多く繰り返し、越えた分の描き換えが組み立ての中に
    ///   来る (置いた側は描き換える前の絵の写しを 4 枚まで持ち、越えると描き切って守る・
    ///   ``createGraphics(_:_:)``)。描き切りまでに組み立てたぶんは、形にならずにそのフレームへ描かれる
    /// - 組み立てている面自身のフレームを中で始める (描き場所の `beginDraw()` の外で始めた
    ///   `createShape { }` の中で、その描き場所の `beginDraw()` を呼ぶなど)。それまでに組み立てた
    ///   ぶんは描かれずに捨てられる
    ///
    /// ## 座標は形自身のもの
    ///
    /// 組み立ての間、変換は畳まれている。どこで組み立てても同じ形になり、
    /// ``shape(_:_:_:)`` の与える位置がそのまま形の原点になる。
    ///
    /// **畳まれるのは組み立てに入る時点までで、中で書いた変換は形に焼き付く。**
    /// 下のように 1 つの形の中で置き場所を書き分けられ、`setup()` で組み立てても
    /// `draw()` で組み立てても同じ形になる。
    ///
    /// <!-- example: 文脈 var leaf: Shape! -->
    /// ```swift
    /// let cluster = Shape.group(
    ///     (0..<9).map { index in
    ///         createShape {
    ///             push()
    ///             translate(Float(index % 3) * 46, Float(index / 3) * 46)
    ///             rotate(Float(index) * 0.4)
    ///             shape(leaf)
    ///             pop()
    ///         }
    ///     })
    /// ```
    ///
    /// ## 組にしても描く回数は増えない
    ///
    /// ``Shape/group(_:)`` と `+` は形を**1 本の頂点の並びへ畳む**。子の一覧を持って
    /// 1 つずつ描く作りではないので、「保持にしたのに速くならない」が起きない。
    public func createShape(_ body: () -> Void) -> Shape { canvas.createShape(body) }

    /// 保持した形を、**置き場所ぶんだけまとめて置く**。
    ///
    /// 同じ形をたくさん置くときは、これがいちばん速い。形の頂点は 1 度しか置かれず、
    /// 置き場所の数だけ描き足される — 1 万個置いても**描く回数は 1 回**になる。
    ///
    /// ```swift
    /// let grain = createShape { box(6) }
    /// var places: [Placement] = []
    /// for _ in 0..<5000 {
    ///     places.append(
    ///         Placement(
    ///             x: random(width), y: random(height),
    ///             rotation: SIMD3(0, random(2 * Float.pi), 0)))
    /// }
    /// shape(grain, at: places)
    /// ```
    ///
    /// **1 つずつ置いたときと同じ絵になる。** `push()` / `translate()` / `pop()` の
    /// 繰り返しで書いても、まとめて渡しても、経路は 1 本しかない。
    ///
    /// ``Placement/fill`` を渡すと、その置き場所の色に**掛かる** (渡さなければ何も
    /// 掛からない)。
    public func shape(_ shape: Shape, at placements: [Placement]) {
        canvas.shape(shape, at: placements)
    }

    /// 保持した形を置く。
    ///
    /// 色は形が持っているものが使われ、置く場所といまの変換が効く。
    ///
    /// **たくさん置くときは shape(_:at:) を使う。** こちらは 1 回ごとに頂点を
    /// 置き直すので、置く数だけ描く回数が増える。
    public func shape(_ shape: Shape, _ x: some ScalarConvertible = 0, _ y: some ScalarConvertible = 0) {
        let (x, y) = (x.asFloat, y.asFloat)
        canvas.shape(shape, x, y)
    }
}
