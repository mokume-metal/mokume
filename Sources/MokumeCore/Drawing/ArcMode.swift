/// 円弧 (``SketchPart/arc(_:_:_:_:_:_:_:)``) の、塗りと輪郭の閉じ方。
///
/// 弧の 2 つの端をどう扱うかを決める。Processing・p5.js の `OPEN`・`CHORD`・`PIE` に当たる。
/// **引数に渡さない `arc` は、塗りは ``pie``・輪郭は ``open`` の形になる** (手本の既定と同じ)。
/// 塗りと輪郭が違う形になるので、どちらか 1 つの値では書けない。
///
/// | 閉じ方 | 塗り | 輪郭 |
/// | --- | --- | --- |
/// | (渡さない) | 扇 | 開いた弧 |
/// | ``pie`` | 扇 | 扇の周 (中心への 2 本の半径と弧) |
/// | ``chord`` | 弧の両端を弦で結んだ形 | 弦で閉じた形の周 |
/// | ``open`` | 弧の両端を弦で結んだ形 | 開いた弧 |
///
/// 一周の弧 (終わりの角度が始まりの角度より 2π 以上大きい) は、どの閉じ方でも楕円と同じ形になる。
///
/// どの閉じ方も、塗りと輪郭を 1 つの図形として、縁を滑らかに描く (引数なしの `arc` も同じ)。
/// 扇の中心と弧の両端、弦で結んだ形の弦と弧の継ぎ目の角は、``SketchPart/strokeJoin(_:)`` によらず丸く繋ぐ。
public nonisolated enum ArcMode: Sendable, Equatable {
    /// 輪郭を閉じない。弧だけが引かれ、両端には ``SketchPart/strokeCap(_:)`` の端の形が付く。
    ///
    /// 塗りは、弧の両端を弦で結んだ形になる。**引数に渡さない `arc` の塗り (扇) とは違う。**
    case open
    /// 弧の両端を弦 (まっすぐな線) で結んで閉じる。塗りも輪郭も、閉じた形になる。
    case chord
    /// 中心から弧の両端へ半径を引いて閉じる。塗りも輪郭も、扇になる。
    case pie
}
