/// 線の端の形。
///
/// 太い線を引くと、端をどう仕上げるかが見えるようになる。太さ 1 の線では 3 つとも
/// ほとんど同じに見えるので、**確かめるときは太さを振る**。
public nonisolated enum StrokeCap: Sendable, Equatable {
    /// 端を丸める (既定)。
    case round
    /// 与えた長さちょうどで切る。
    case square
    /// 与えた長さから、太さの半分だけはみ出させる。
    ///
    /// ``square`` と同じ四角い端だが、線が半分ぶん長くなる。目盛りのように
    /// 「線の端をぴったり合わせたい」ときに効く。
    case project
}

/// 線の折れ目の形。
///
/// 折れ線と、閉じた図形の輪郭の角に効く。**曲線の刻みの継ぎ目には効かない** —
/// 継ぎ目は角ではないので、どの形でも丸く繋ぐ ([#1409])。曲線の終点と通過点は
/// 置いた点なので、そこで折れれば角として扱う。扇形 (``Sketch/arc(_:_:_:_:_:_:)``) の
/// 中心と弧の両端は、どの形でも丸く繋ぐ。
///
/// [#1409]: https://github.com/mokume-metal/mokume/issues/1409
public nonisolated enum StrokeJoin: Sendable, Equatable {
    /// 角を尖らせる (既定)。
    ///
    /// 2 本の線の外側の縁を延ばして尖らせ、尖りが角から線幅 × √2 / 2 より先へ伸びるときは、
    /// そこで角の二等分線に垂直に切る。直角 (矩形の角) では尖りがちょうどその長さなので、
    /// 切られずに尖る。それより鋭い角では先が平らに切られ、極端には伸びない。
    ///
    /// - Note: 伸びの限界を線ごとに選ぶ口は無い。扇形の角は、折れ目の形によらず丸く出る。
    case miter
    /// 角を削ぐ。
    ///
    /// 尖りを、角から線幅の半分の所で角の二等分線に垂直に切る。矩形の角は 45° で削がれる。
    case bevel
    /// 角を丸める。
    case round
}
