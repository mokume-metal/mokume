import Metal

// `@MainActor` を明示する理由は ``RenderDevice`` の冒頭と同じ (release のテストビルドで
// 暗黙の既定隔離が見失われる・#761)。

/// フレームごとに CPU が書く置き場の環 — **いまどのスロットへ書いてよいか**を持つ。
///
/// ## なぜ環にするのか
///
/// 描き切りは GPU の完了を待たずに返る ([#727])。だが置き場が 1 本しか無いと、次の
/// フレームが書く前に「投入済みの全部」が終わるのを待つしかなく、待っている間 GPU は
/// 空になる — パイプラインの深さが 1 のままである ([#754])。スロットを分ければ、次の
/// フレームは**別の置き場**へ書けるので、待つのは「そのスロットを最後に読んだ投入」
/// だけで済む。
///
/// ## 何を守るか
///
/// > いまのスロットの置き場を読む投入は、すべて終わっている。
///
/// ``advance()`` がその 1 行を保証し、``noteSubmission()`` が「このスロットを読む投入」を
/// 記録する。**両方を通さない経路を作らない** — 記録しない投入があると、そのスロットは
/// 「いつ読み終わるか分からないまま書いてよい」ことになる。
///
/// ## GPU 側の順序には触れない
///
/// 投入どうしの実行順は ``RenderDevice`` が投入のたびに積む待ち合わせが保っている
/// (#727 の不変条件 2)。だから GPU が読むもの (焼いた影の面・効果の控え・描画先) は
/// 環にしなくてよい。**環が要るのは CPU が書く側だけ**である。
///
/// ## 速さを買っているのは待ちではなく、置き場が分かれていること
///
/// **``advance()`` の待ちは、たいていの経路で 1 度も止まらない。** コマンドの置き場の環
/// (``RenderDevice/beginCommands()``) が同じ深さで先に待っており、投入は順に終わるので、
/// そちらの待ちがこちらの要求を丸ごと覆うためである — 描き切りが 1 フレームに 1 本しか
/// 投入しない経路では両者はちょうど重なり、差し出しを挟む経路ではコマンドの環のほうが
/// 厳しくなる。
///
/// **それでも待ちを置くのは、この型が自分の不変条件を自分で守るためである。** 覆いは
/// 「置き場の本数が両者で同じ」「書く前に必ずコマンドを開く」という 2 つの偶然に乗って
/// いて、どちらもこの型の外にある。片方が動いた日に静かに壊れる規律は置かない。止まらない
/// 待ちの費用は、合図の値を 1 度読むことだけである。
///
/// [#727]: https://github.com/mokume-metal/mokume/issues/727
/// [#754]: https://github.com/mokume-metal/mokume/issues/754
@MainActor final class FrameRing {
    private let gpu: RenderDevice

    /// スロットごとの「そのスロットの置き場を最後に読んだ投入の番号」。まだ無ければ 0。
    private var readers: [UInt64]

    /// いま CPU が書いてよいスロット。
    private(set) var slot: Int

    /// スロットの本数。
    var slotCount: Int { readers.count }

    /// コマンドの置き場と同じ本数で作る。
    init(gpu: RenderDevice) {
        self.gpu = gpu
        self.readers = Array(repeating: 0, count: max(1, gpu.slotCount))
        // 最初の ``advance()`` が 0 番から始まるように、1 つ手前から始める
        self.slot = readers.count - 1
    }

    /// 次のスロットへ進み、**そのスロットを読む投入が終わるまで待つ**。
    ///
    /// 書き始める直前に 1 度だけ呼ぶ。既に終わっていれば何もせずに返るので、呼ぶ側は
    /// 「待つかもしれない」ことだけを知っていればよい。
    func advance() throws(RenderFailure) {
        slot = (slot + 1) % readers.count
        try gpu.waitForSubmission(readers[slot])
    }

    /// 直前の投入を、**いまのスロットを読む投入**として覚える。投入の直後に呼ぶ。
    ///
    /// 覚えるのは番号だけで、投入そのものは持たない。次にこのスロットが回ってきたとき、
    /// その番号まで待てば「このスロットの置き場を読む者はもういない」ことになる。
    func noteSubmission() {
        readers[slot] = gpu.submissionCount
    }
}
