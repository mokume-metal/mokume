import Foundation

@testable import MokumeCore

extension RenderDevice {
    /// 絵や結果が期待と違ったときに、落ちた表明の文面へ添える説明。**この土台に打ち切りの
    /// 記録があれば、その回数と最後の理由を名乗る。無ければ、記録が無いことを名乗る。**
    ///
    /// **無いときも黙らない。** 黙ると、記録の上で「見て、打ち切りは無かった」と「打ち切りを
    /// 見ていない口」とが区別できない。
    ///
    /// **回数は、この土台を作ってからの累計である。** 記録は土台が生きている間溜まり続け、
    /// どの表明の間に起きたかは持たない。文面もそのとおりに言う。
    ///
    /// GPU が仕事を打ち切ると、その絵は 1 画素も書かれないのに合図は投入の順に進むので、
    /// **待ちは成立したまま空の絵が読める** ([#1065])。これが無いと、症状は
    /// 「絵が黒い」「何成分違う」としてしか残らず、原因を console の知らせと機械の込み具合まで
    /// 辿り直すことになる — [#1063] と [#1812] の 1 回ずつがまさにそれだった。文面に載せれば、
    /// 記録の正本 (xunit) と run の要約にも残る。
    ///
    /// **表明を落とす条件にはしない。** 打ち切られたのが絵を作った投入とは限らず、
    /// 差し出しも読み戻しも同じ土台を通る。条件にすると**絵が無事な回まで赤くなる**
    /// (実測: 複数フレームを回す 2 本が、絵の食い違いなしにこれだけで落ちた)。
    ///
    /// **表明の文面 (`#expect` の 2 つ目の引数) の中で呼ぶ。** 文面は表明が落ちたときにだけ
    /// 組み立てられるので、下の待ちは通った表明の実行時間に出ない。
    ///
    /// **投げる読む口で読んだ絵には要らない** ([#1932])。`readPixels()`・`encodeForDisplay(scale:)`・
    /// `writePNG(to:)`・`renderFrame(to:)` は、返す絵が拠った投入 (同じ面で前に判定した読みの後に
    /// 積まれた投入すべて) の打ち切りを結末が届くまで待って見つけ、表明より前に `.workDropped` を
    /// 投げる。理由は失敗の 1 行目に載るので、検査はここを呼ばなくても打ち切りを名乗る。ここが
    /// 名乗れるのは、それ以外 — 投げない口 (`pixels`・`get`・出口の絵・観測) で読んだ値の表明と、
    /// 範囲の外 (前の判定より前) の打ち切りである。どのファイルへ広げるかは、巻き添えらしい赤を見た
    /// 回に、その赤を直す PR で決める ([#1930] の経緯)。
    ///
    /// [#1063]: https://github.com/mokume-metal/mokume/issues/1063
    /// [#1065]: https://github.com/mokume-metal/mokume/issues/1065
    /// [#1812]: https://github.com/mokume-metal/mokume/issues/1812
    /// [#1930]: https://github.com/mokume-metal/mokume/issues/1930
    /// [#1932]: https://github.com/mokume-metal/mokume/issues/1932
    func faultNote() -> String {
        // **少し待ってから読む。** 結末は Metal 側の糸から届くので、絵を読み終えた時点
        // ではまだ来ていないことがある (実測: 絵が空で落ちた 4 回とも、その時点では 0 だった)。
        // ここを通るのは**表明が既に落ちた後**だけなので、待っても普段の実行時間には出ない
        if commandFaultCount == 0 { Thread.sleep(forTimeInterval: 0.1) }
        guard commandFaultCount > 0 else {
            // 待っても届かなかった結末はありうるので、「無かった」とは言い切らない
            return """

                (GPU の打ち切りの記録なし: この土台には、表明が落ちてから 0.1 秒待った時点で\
                打ち切りの記録が 1 つも無い。それより遅れて届いた打ち切りは、ここには載らない)
                """
        }
        return """

            (この土台では、これまでに GPU が仕事を \(commandFaultCount) 回打ち切っている。\
            最後の理由: \(lastCommandFault ?? "理由は届いていない")。
            打ち切られた投入は 1 画素も書かれないので、食い違いはそのせいかもしれない)
            """
    }
}
